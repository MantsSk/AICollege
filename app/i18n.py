def get_language(request: Request) -> str:
    lang = request.query_params.get("lang") or request.cookies.get("language")
    if lang in SUPPORTED_LANGUAGES:
        return lang
    return DEFAULT_LANGUAGE


def make_translator(lang: str) -> Callable[..., str]:
    def translate(key: str, **kwargs) -> str:
        text = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
        return text.format(**kwargs) if kwargs else text

    return translate


def i18n_context(request: Request) -> dict:
    lang = get_language(request)
    return {
        "lang": lang,
        "languages": SUPPORTED_LANGUAGES,
        "_": make_translator(lang),
    }
